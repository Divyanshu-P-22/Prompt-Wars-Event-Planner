/**
 * @file index.ts
 * @description Core TypeScript type definitions and interfaces for CelebrateAI.
 * Defines models for events, budgets, timelines, vendors, AI planning structures,
 * recommendations, chat messages, and multi-step wizard form submissions.
 */

/**
 * Supported event categories in CelebrateAI.
 */
export type EventType = 'wedding' | 'birthday' | 'community';

/**
 * Current lifecycle status of an event.
 */
export type EventStatus = 'planning' | 'in_progress' | 'completed' | 'cancelled';

/**
 * Priority levels for planning tasks, milestones, and budget allocations.
 */
export type Priority = 'low' | 'medium' | 'high' | 'critical';

/**
 * Procurement / payment status for individual budget line items.
 */
export type BudgetItemStatus = 'estimated' | 'quoted' | 'booked' | 'paid';

/**
 * Progress status for timeline tasks and milestones.
 */
export type TimelineItemStatus = 'pending' | 'in_progress' | 'completed' | 'overdue';

/**
 * Engagement lifecycle status for service vendors.
 */
export type VendorStatus = 'researching' | 'contacted' | 'negotiating' | 'booked' | 'paid';

/**
 * User-configured preferences and stylistic desires for an event.
 */
export interface EventPreferences {
  theme?: string;
  cuisine?: string[];
  style?: string; // 'formal' | 'casual' | 'themed' | 'traditional'
  colorScheme?: string[];
  specialRequirements?: string;
  culturalConsiderations?: string;
}

/**
 * AI-generated high-level category breakdown of the event budget.
 */
export interface BudgetCategory {
  category: string;
  percentage: number;
  estimatedAmount: number;
  description: string;
  priority: Priority;
}

/**
 * User-tracked or AI-instantiated line item within the event budget.
 */
export interface BudgetItem {
  id: string;
  category: string;
  name: string;
  estimatedCost: number;
  actualCost: number;
  status: BudgetItemStatus;
  notes: string;
}

/**
 * High-level milestone generated during AI event planning.
 */
export interface TimelineMilestone {
  title: string;
  description: string;
  dueDate: string;
  category: string;
  priority: Priority;
}

/**
 * Actionable task or milestone tracked on the event schedule.
 */
export interface TimelineItem {
  id: string;
  title: string;
  description: string;
  dueDate: string;
  status: TimelineItemStatus;
  priority: Priority;
  category: string;
}

/**
 * Recommended vendor category guidance provided by AI.
 */
export interface VendorRecommendation {
  category: string;
  importance: string;
  estimatedBudget: number;
  bookingTimeline: string;
  tips: string[];
}

/**
 * Active vendor entity managed by the user for an event.
 */
export interface Vendor {
  id: string;
  name: string;
  category: string;
  contact: string;
  email: string;
  phone: string;
  estimatedCost: number;
  status: VendorStatus;
  notes: string;
  rating: number;
}

/**
 * Creative theme and aesthetic recommendation generated by AI.
 */
export interface ThemeSuggestion {
  name: string;
  description: string;
  colorPalette: string[];
  keyElements: string[];
  moodKeywords: string[];
}

/**
 * Complete AI-generated comprehensive event blueprint.
 */
export interface AIPlan {
  overview: string;
  highlights: string[];
  budgetBreakdown: BudgetCategory[];
  timelineMilestones: TimelineMilestone[];
  vendorRecommendations: VendorRecommendation[];
  themeSuggestions: ThemeSuggestion[];
  tips: string[];
}

/**
 * Main application data model representing an entire celebration event.
 */
export interface CelebrateEvent {
  id: string;
  name: string;
  type: EventType;
  status: EventStatus;
  date: string;
  location: string;
  guestCount: number;
  totalBudget: number;
  description: string;
  preferences: EventPreferences;
  aiPlan: AIPlan | null;
  budgetItems: BudgetItem[];
  timelineItems: TimelineItem[];
  vendors: Vendor[];
  createdAt: string;
  updatedAt: string;
}

/**
 * Conversational message exchanged between user and AI event planner assistant.
 */
export interface AIMessage {
  id: string;
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
}

/**
 * Tailored recommendation item for specific event categories.
 */
export interface AIRecommendation {
  id: string;
  category: string;
  title: string;
  description: string;
  details: string[];
  tags: string[];
}

/**
 * Form payload collected across the event creation wizard steps.
 */
export interface WizardFormData {
  type: EventType | '';
  name: string;
  date: string;
  location: string;
  guestCount: number;
  totalBudget: number;
  description: string;
  preferences: EventPreferences;
}
